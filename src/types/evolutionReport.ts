export interface ScoreDimension {
  key: 'adherence' | 'performance' | 'functionalCapacity' | 'mobility' | 'bodyComposition';
  label: string;
  score: number; // 0-100
  weight: number; // e.g. 20 (sum of weights = 100)
  enabled: boolean;
  hasEnoughData: boolean;
  details: string;
  metrics: string[];
}

export interface ReportEvolutionScore {
  overallScore: number; // 0-100
  dimensions: {
    adherence: ScoreDimension;
    performance: ScoreDimension;
    functionalCapacity: ScoreDimension;
    mobility: ScoreDimension;
    bodyComposition: ScoreDimension;
  };
  methodologyNotes: string;
}

